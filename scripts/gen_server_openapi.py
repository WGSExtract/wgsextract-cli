"""Build the default server OpenAPI document and, optionally, GUI transport types."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]

from scripts.json_lines import dump_lines  # noqa: E402
from wgsextract_cli.server.http_api import openapi_document  # noqa: E402

OPENAPI = ROOT / "out/contracts/wgsextract.server.openapi.json"
GUI_TYPES = ROOT / "gui/app/shared/generated/server-transport.ts"
GUI_CERTIFICATIONS = ROOT / "gui/app/shared/generated/command-certifications.ts"


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).removeprefix("#/components/schemas/")
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts_type(item) for item in schema["anyOf"]))
    match schema.get("type"):
        case "array":
            return f"({_ts_type(schema['items'])})[]"
        case "object":
            values = schema.get("additionalProperties", True)
            if values is not False and "properties" not in schema:
                return f"Record<string, {_ts_type(values) if isinstance(values, dict) else 'unknown'}>"
        case "integer" | "number":
            return "number"
        case "string" | "boolean" | "null":
            return str(schema["type"])
        case None if not schema:
            return "unknown"
    raise ValueError(f"Unsupported transport schema: {schema!r}")


def render_typescript(document: dict[str, Any]) -> str:
    """Render the response component interfaces, excluding operation inputs."""
    components = document["components"]["schemas"]
    inputs = {
        operation["requestBody"]["content"]["application/json"]["schema"][
            "$ref"
        ].removeprefix("#/components/schemas/")
        for path, methods in document["paths"].items()
        if path.startswith("/v1/ops/") and (operation := methods.get("post"))
    }
    lines = ["// Generated by scripts/gen_server_openapi.py. Do not edit.", ""]
    for name, schema in components.items():
        if name in inputs:
            continue
        lines.append(f"export interface {name} {{")
        for key, field in schema["properties"].items():
            optional = "" if key in schema.get("required", ()) else "?"
            lines.append(f"    {key}{optional}: {_ts_type(field)};")
        lines.extend(["}", ""])
    return "\n".join(lines)


def build_openapi(output: Path, *, gui_types: Path | None = None) -> None:
    document = openapi_document()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        dump_lines(document, expand=(("paths",), ("components", "schemas"))),
        encoding="utf-8",
        newline="\n",
    )
    if gui_types is not None:
        gui_types.parent.mkdir(parents=True, exist_ok=True)
        gui_types.write_text(
            render_typescript(document),
            encoding="utf-8",
            newline="\n",
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OPENAPI)
    parser.add_argument("--gui", action="store_true")
    args = parser.parse_args()
    build_openapi(args.output, gui_types=GUI_TYPES if args.gui else None)
    if args.gui:
        from wgsextract_cli.cli.help_index import build_index
        from wgsextract_cli.core.certification import CertificationLevel

        levels = " | ".join(json.dumps(level.value) for level in CertificationLevel)
        commands = {
            entry["path"]: entry["certification"] for entry in build_index()["commands"]
        }
        GUI_CERTIFICATIONS.write_text(
            "// Generated from the CLI help index. Do not edit.\n"
            f"type CertificationLevel = {levels};\n"
            "export const commandCertifications: Readonly<Record<string, CertificationLevel | undefined>> = "
            + json.dumps(commands, indent=4, sort_keys=True)
            + ";\n",
            encoding="utf-8",
            newline="\n",
        )


if __name__ == "__main__":
    main()
