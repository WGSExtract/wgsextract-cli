#!/usr/bin/env python3
"""Generate docs/configuration.md from the config.toml schema.

python scripts/gen_config_docs.py          # rewrite docs/configuration.md
python scripts/gen_config_docs.py --check  # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from wgsextract_cli.core.config import CONFIG_ALIASES  # noqa: E402
from wgsextract_cli.core.settings_schema import (  # noqa: E402
    DEV_SETTINGS,
    DEV_TABLE,
    MOVED_TO_DEV,
    SERVER_SETTINGS,
    SETTINGS,
    SettingField,
)

OUTPUT = ROOT / "docs" / "configuration.md"
GUIDE = ROOT / "docs" / "data" / "configuration-guide.md"
TYPES = {
    "bool": "boolean",
    "int": "integer",
    "float": "number",
    "str": "string",
    "paths": "string or array of strings",
    "table": "tables",
    "threads": "integer or `auto`",
}


def value_type(setting: SettingField) -> str:
    info = setting.info
    if info.choices:
        return " or ".join(f"`{choice}`" for choice in info.choices)
    text = TYPES[setting.kind]
    if info.minimum is not None and info.maximum is not None:
        text += f", {info.minimum:g} to {info.maximum:g}"
    elif info.minimum is not None:
        text += f", at least {info.minimum:g}"
    if info.path:
        text += ", path (`~` expands)"
    return text


def default(value: object) -> str:
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, str):
        return f'`"{value}"`'
    return f"`{value}`"


def table(schema: Mapping[str, SettingField]) -> list[str]:
    lines = ["| Setting | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, setting in schema.items():
        description = setting.info.help.replace("|", "\\|")
        lines.append(
            f"| `{name}` | {value_type(setting)} | {default(setting.default)} | "
            f"{description} |"
        )
    return lines


def render() -> str:
    aliases = ", ".join(
        f"`{alias}` (`{name}`)" for alias, name in sorted(CONFIG_ALIASES.items())
    )
    moved = ", ".join(
        f"`{old}` (now `{new}`)" for old, new in sorted(MOVED_TO_DEV.items())
    )
    lines = [
        "# config.toml settings",
        "",
        "<!-- Generated by scripts/gen_config_docs.py from",
        "src/wgsextract_cli/core/settings_schema.py; run `just regen`. -->",
        "",
        "WGS Extract reads its settings from config.toml: `wgsextract config` "
        "prints where it is and every setting's value, and `--config PATH` "
        "picks another file for one run. Command-line options override "
        "settings for a run.",
        "",
        "config.toml lives in the users workspace, `~/wgs-extract` "
        "(`%USERPROFILE%\\wgs-extract` on Windows), beside the default My "
        "Genomes library (`mygenomes/`): the folders you manage and may want "
        "on another disk. An install that "
        "already keeps config.toml where earlier versions did (the per-user "
        "config folder, `~/.config/wgsextract` on macOS) keeps using it. "
        "Reference data, reference genomes and temporary files stay in the "
        "CLI's own data folder unless config.toml names other folders. The "
        "WGS Extract desktop app keeps its settings in the same folder, so "
        "the two share them.",
        "",
        "If both a legacy CLI config and a users-workspace config exist, the "
        "CLI keeps using the legacy file and warns with both paths. Use "
        "`--config PATH` to select the other explicitly. Opening the desktop "
        "app does not change this precedence or erase saved advanced settings.",
        "",
        "Without output_directory, a command writes to a `wgse/` folder beside "
        "its input from the lab (a BAM or CRAM, else FASTQs, else a VCF, else "
        "a raw microarray file), or beside an input already in a `wgse/` "
        "folder. The folder of the lab's original files stays untouched: only "
        "indexes that must sit beside their files are written there, and "
        "writing a BAM, CRAM, FASTQ, VCF or microarray file into it warns "
        "(`primary_overwrite`).",
        "",
        "Every value is checked when the file loads: a value of the wrong type, "
        "outside its range or not one of its choices stops the run with an "
        "error that names the setting and what it expects. An unknown setting "
        "is ignored with a warning that suggests the closest name.",
        "",
        "<!-- Usage guide: edit docs/data/configuration-guide.md, then regenerate. -->",
        # The hand-written fragment lives one directory below the output page.
        GUIDE.read_text(encoding="utf-8").replace("](../", "](").rstrip(),
        "",
        "## Settings",
        "",
        *table(SETTINGS),
        "",
        f"Older names still read: {aliases}.",
        "",
        "## The [server] table",
        "",
        "Operator opt-ins for HTTP/JSON listening and viewer files. See "
        "[server mode](server.md#remote-http-access) for exposure and TLS requirements.",
        "",
        *table(SERVER_SETTINGS),
        "",
        f"## The [{DEV_TABLE}] table",
        "",
        "Developer and test settings live in their own table, at the end of "
        "config.toml (after a table header, every key belongs to that table):",
        "",
        "```toml",
        f"[{DEV_TABLE}]",
        "download_cache = true",
        "```",
        "",
        *table(DEV_SETTINGS),
        "",
        "These used to be top-level settings; a config.toml that still has "
        f"one there fails to load, naming its place in [{DEV_TABLE}]: {moved}.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run 'just regen'.")
            raise SystemExit(1)
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
