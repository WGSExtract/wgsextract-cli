"""Emit raw server transport and canonical result/report writer contracts."""

from __future__ import annotations

import json
import types
from collections.abc import Mapping
from dataclasses import is_dataclass
from typing import (
    Annotated,
    Literal,
    Protocol,
    Union,
    cast,
    get_args,
    get_origin,
    get_type_hints,
    is_typeddict,
)

from wgsextract_cli.core.output_schema import (
    Constraints,
    _dataclass_hints,
    _dataclass_required,
)
from wgsextract_cli.core.report_documents import ReportDocument
from wgsextract_cli.core.results import (
    CommandResult,
    FileRecord,
    Provenance,
    ReferenceRecord,
    ResultError,
    ResultWarning,
)
from wgsextract_cli.server import transport


class _Keys(Protocol):
    __required_keys__: frozenset[str]


def _hints(model: object) -> dict[str, object]:
    if not isinstance(model, type):
        raise TypeError(f"Expected a writer record: {model!r}")
    return (
        _dataclass_hints(model)
        if is_dataclass(model)
        else get_type_hints(model, include_extras=True)
    )


def typescript_records(
    roots: Mapping[object, str], *, names: Mapping[object, str] | None = None
) -> str:
    """Render a supported writer graph, rejecting ambiguous or invalid records."""
    models = dict(roots)
    if len(set(models.values())) != len(models):
        raise TypeError("Duplicate TypeScript record names.")
    visited: set[object] = set()
    names = names or {}

    def visit(tp: object) -> None:
        if is_typeddict(tp) or (isinstance(tp, type) and is_dataclass(tp)):
            if tp in visited:
                return
            visited.add(tp)
            if tp not in models:
                if not isinstance(tp, type):
                    raise TypeError(f"Expected a writer record: {tp!r}")
                name = names.get(tp, tp.__name__)
                if name in models.values():
                    raise TypeError(f"Duplicate TypeScript record name: {name}")
                models[tp] = name
            for annotation in _hints(tp).values():
                visit(annotation)
            return
        origin = get_origin(tp)
        args = get_args(tp)
        if origin is Annotated:
            visit(args[0])
        elif origin is not Literal:
            for annotation in args:
                visit(annotation)

    for model in roots:
        visit(model)

    def describe(tp: object) -> str:
        if tp in models:
            return models[tp]
        origin = get_origin(tp)
        args = get_args(tp)
        if origin is Annotated:
            enum = None
            for metadata in args[1:]:
                if not isinstance(metadata, Constraints):
                    raise TypeError(f"Unsupported schema metadata: {metadata!r}")
                if metadata.enum is not None:
                    enum = metadata.enum
            if enum is not None:
                if not enum:
                    raise TypeError("An output enum must have at least one value.")
                values = " | ".join(json.dumps(value) for value in enum)
                return f"({describe(args[0])}) & ({values})"
            return describe(args[0])
        if origin is Literal:
            return " | ".join(json.dumps(value) for value in args)
        if origin in (Union, types.UnionType):
            return " | ".join(dict.fromkeys(describe(arg) for arg in args))
        if origin is list and len(args) == 1:
            return f"({describe(args[0])})[]"
        if origin is dict and len(args) == 2 and args[0] is str:
            return f"Record<string, {describe(args[1])}>"
        primitive = {
            str: "string",
            int: "number",
            float: "number",
            bool: "boolean",
            type(None): "null",
            object: "unknown",
        }
        if tp in primitive:
            return primitive[tp]
        raise TypeError(f"Unsupported transport TypeScript annotation: {tp!r}")

    lines = ["// Generated by scripts/gen_server_contracts.py. Do not edit.", ""]
    for model, name in models.items():
        hints = _hints(model)
        required = (
            _dataclass_required(model)
            if isinstance(model, type) and is_dataclass(model)
            else cast(_Keys, model).__required_keys__
        )
        lines.append(f"export interface {name} {{")
        for key, tp in hints.items():
            optional = "" if key in required else "?"
            lines.append(f"    {key}{optional}: {describe(tp)};")
        lines.extend(["}", ""])
    return "\n".join(lines)


def typescript() -> str:
    return typescript_records(
        {
            model: name
            for name, model in vars(transport).items()
            if is_typeddict(model) and not name.endswith("Required")
        }
    )


def result_typescript() -> str:
    return typescript_records(
        {CommandResult: "ResultDocumentRecord"},
        names={
            FileRecord: "ResultFileRecord",
            ResultWarning: "ResultWarningRecord",
            ResultError: "ResultErrorRecord",
            Provenance: "ResultProvenanceRecord",
            ReferenceRecord: "ResultReferenceRecord",
        },
    )


def report_typescript() -> str:
    return typescript_records({ReportDocument: "ReportDocumentRecord"})
