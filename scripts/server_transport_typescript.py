"""Emit TypeScript for the limited server transport and result-leaf model graph."""

from __future__ import annotations

import json
import types
from dataclasses import is_dataclass
from typing import (
    Annotated,
    Literal,
    Protocol,
    Union,
    cast,
    get_args,
    get_origin,
    get_type_hints,
    is_typeddict,
)

from wgsextract_cli.core.output_schema import _dataclass_hints
from wgsextract_cli.core.results import FileRecord, ResultError, ResultWarning
from wgsextract_cli.server import transport


class _Keys(Protocol):
    __required_keys__: frozenset[str]


def typescript() -> str:
    models: dict[object, str] = {
        model: name
        for name, model in vars(transport).items()
        if is_typeddict(model) and not name.endswith("Required")
    }
    models.update(
        {
            FileRecord: "ResultFileRecord",
            ResultWarning: "ResultWarningRecord",
            ResultError: "ResultErrorRecord",
        }
    )

    def describe(tp: object) -> str:
        if tp in models:
            return models[tp]
        origin = get_origin(tp)
        args = get_args(tp)
        if origin is Annotated:
            return describe(args[0])
        if origin is Literal:
            return " | ".join(json.dumps(value) for value in args)
        if origin in (Union, types.UnionType):
            return " | ".join(dict.fromkeys(describe(arg) for arg in args))
        if origin is list and len(args) == 1:
            return f"({describe(args[0])})[]"
        if origin is dict and len(args) == 2 and args[0] is str:
            return f"Record<string, {describe(args[1])}>"
        primitive = {
            str: "string",
            int: "number",
            float: "number",
            bool: "boolean",
            type(None): "null",
            object: "unknown",
        }
        if tp in primitive:
            return primitive[tp]
        raise TypeError(f"Unsupported transport TypeScript annotation: {tp!r}")

    lines = ["// Generated by scripts/gen_server_contracts.py. Do not edit.", ""]
    for model, name in models.items():
        if isinstance(model, type) and is_dataclass(model):
            hints = _dataclass_hints(model)
            required = frozenset(hints)
        else:
            hints = get_type_hints(model, include_extras=True)
            required = cast(_Keys, model).__required_keys__
        lines.append(f"export interface {name} {{")
        for key, tp in hints.items():
            optional = "" if key in required else "?"
            lines.append(f"    {key}{optional}: {describe(tp)};")
        lines.extend(["}", ""])
    return "\n".join(lines)
