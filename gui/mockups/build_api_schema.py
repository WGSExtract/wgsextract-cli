#!/usr/bin/env python3
"""Write shared/data/api-schema.js: every server operation's parameters, from
the OpenAPI document the server publishes (generated from the typed API's
Params, #929), with each parameter's command-line flag from the CLI snapshot.

The v2 tool pages build their fields and requests from it, and the mock
server checks requests against it, so the mockups can't drift from the API.
Run after the API changes (CI checks it is current):

    python3 gui/mockups/build_api_schema.py           # write
    python3 gui/mockups/build_api_schema.py --check   # fail if stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OPENAPI = ROOT / "src/wgsextract_cli/assets/schemas/wgsextract.server.openapi.json"
SNAPSHOT = ROOT / "tests/fixtures/api_cli_snapshot.json"
OUT = HERE / "shared/data/api-schema.js"
PREFIX = "/v1/ops/"
FIRST_SENTENCE = re.compile(r"^(.+?[.!?])(\s|$)", re.DOTALL)
# Parser entries that aren't parameters of an operation
NOT_PARAMS = {"help", "help_all", "json", "quiet", "debug", "log_file", "config_path", "_result_file", "parent_pid"}

HEADER = """/* GENERATED by gui/mockups/build_api_schema.py from the server's OpenAPI
 * document and the CLI snapshot; don't edit. Every operation's parameters:
 * WGSMSchema.ops[op] = { summary, required, fields: { name: { type,
 * nullable, enum, default, path, items, about, flag } } }. flag is the
 * command-line spelling: ["--ref"], ["--parallel", "--no-parallel"], or
 * [] for a positional argument. Loads in the browser and in Node. */
"""


def short(text: str) -> str:
    text = " ".join((text or "").split())
    match = FIRST_SENTENCE.match(text)
    return match.group(1) if match else text


def field(spec: dict[str, Any]) -> dict[str, Any]:
    types = spec.get("type", "string")
    types = types if isinstance(types, list) else [types]
    out: dict[str, Any] = {"type": next((t for t in types if t != "null"), "string")}
    if "null" in types:
        out["nullable"] = True
    if "enum" in spec:
        out["enum"] = [v for v in spec["enum"] if v is not None]
    if "default" in spec:
        out["default"] = spec["default"]
    if spec.get("format") == "path":
        out["path"] = True
    if out["type"] == "array":
        out["items"] = spec.get("items", {}).get("type", "string")
    if spec.get("description"):
        out["about"] = short(spec["description"])
    return out


def flags(snapshot: dict[str, Any], op: str) -> dict[str, list[str]]:
    command = snapshot.get(op.replace("/", " "))
    if not command:
        return {}
    found: dict[str, list[str]] = {}
    for action in command["parser"]["actions"]:
        dest = action.get("dest")
        if dest is None or dest in NOT_PARAMS:
            continue
        longs = [o for o in action["option_strings"] if o.startswith("--")]
        found[dest] = longs if longs else []
    return found


def build() -> str:
    doc = json.loads(OPENAPI.read_text(encoding="utf-8"))
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))["commands"]
    schemas = doc["components"]["schemas"]
    ops: dict[str, Any] = {}
    for path, item in sorted(doc["paths"].items()):
        if not path.startswith(PREFIX) or "{" in path or "post" not in item:
            continue
        op = path[len(PREFIX) :]
        post = item["post"]
        ref = post["requestBody"]["content"]["application/json"]["schema"]["$ref"]
        params = schemas[ref.rsplit("/", 1)[-1]]
        cli = flags(snapshot, op)
        fields = {}
        for name, spec in params.get("properties", {}).items():
            one = field(spec)
            if name in cli:
                one["flag"] = cli[name]
            fields[name] = one
        ops[op] = {"summary": short(post.get("summary", "")), "required": params.get("required", []), "fields": fields}
    def compact(value: Any) -> str:
        return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))

    lines = ",\n".join(f"    {compact(op)}: {compact(ops[op])}" for op in sorted(ops))
    version = compact(doc.get("info", {}).get("version", ""))
    return (
        HEADER
        + '(function (root) {\n  "use strict";\n'
        + f"  root.WGSMSchema = {{ version: {version}, ops: {{\n{lines},\n  }} }};\n"
        + '})(typeof globalThis !== "undefined" ? globalThis : this);\n'
    )


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
