import { readFile, writeFile } from "node:fs/promises";

const directory = new URL("shared/data/igv/", import.meta.url);
const output = new URL("coverage-demo.js", directory);
const data = {
  bedgraph: await readFile(new URL("coverage.bedgraph", directory), "utf8"),
  bigwig: (await readFile(new URL("coverage.bw", directory))).toString("base64"),
};
const text = `/* Generated by build_coverage_demo.mjs from the tiny public coverage fixtures.
 * The trusted Pages allowlist omits .bedgraph/.bw. Native browser Files
 * exercise manual local-file viewing without a fetch or disguised extension. */
window.WGSM_COVERAGE_DEMO = ${JSON.stringify(data, null, 2)};
`;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== text) throw new Error("Run node gui/mockups/build_coverage_demo.mjs");
} else {
  await writeFile(output, text);
}
