#!/usr/bin/env python3
"""Bundle the SVG icons into icons.js so mockups can draw them inline, also
when opened from file:// (where fetch() of local files is blocked).

The SVG files are the source: lucide/ holds the vendored Lucide icons (ISC,
see lucide/LICENSE) used for generic UI, wgse/ the WGS Extract domain icons.
Run after adding or editing an icon:

    python3 gui/mockups/icons/build_icons.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SETS = ("wgse", "lucide")
SVG_BODY = re.compile(r"<svg\b[^>]*>(.*)</svg>", re.DOTALL)
COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)


def icon_body(path: Path) -> str:
    match = SVG_BODY.search(COMMENT.sub("", path.read_text(encoding="utf-8")))
    if not match:
        raise SystemExit(f"{path}: no <svg> element")
    return re.sub(r">\s+<", "><", match.group(1).strip())


def main() -> int:
    icons: dict[str, dict[str, str]] = {}
    for icon_set in SETS:
        for path in sorted((HERE / icon_set).glob("*.svg")):
            name = path.stem
            if name in icons:
                raise SystemExit(f"{name}: in both {icons[name]['set']} and {icon_set}")
            icons[name] = {"set": icon_set, "body": icon_body(path)}
    ordered = dict(sorted(icons.items()))
    text = (
        "// Generated by build_icons.py from wgse/*.svg and lucide/*.svg; do not edit.\n"
        f"window.WGSM_ICONS = {json.dumps(ordered, indent=1, ensure_ascii=False)};\n"
    )
    (HERE / "icons.js").write_text(text, encoding="utf-8")
    print(f"icons.js: {len(ordered)} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
